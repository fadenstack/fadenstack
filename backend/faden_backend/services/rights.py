"""A change of someone's rights ends their sign-ins: they sign in again, into a new session.

The OWASP Session Management Cheat Sheet: "The session ID must be renewed or regenerated by the web
application after any privilege level change within the associated user session", permission changes and
role switches named; the old one "must be destroyed". Gained or lost alike. Here a person's rights are their
roles, the teams they are in (with the teams' roles), the permissions of those roles and the administrator
right; whoever changes them (an administrator, a sign-in provider's provisioning or group rules, the server's
CLI) goes through :func:`rights_changed`. What a request may reach beyond that (an agent's grants, a shared
skill) is checked when the request comes (ASVS 5.0 V8.3.2), in the backend and in the gateway.

Each person whose sign-ins end this way is recorded (``user.sign_ins.ended``, with the cause), so the audit
trail says why someone was signed out.
"""

from __future__ import annotations

import json
import uuid
from collections.abc import Iterable

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from faden_backend.db.dao.audit_dao import AuditDAO
from faden_backend.db.models.containers import AuditResult
from faden_backend.db.models.groups import GroupRole, UserGroup
from faden_backend.db.models.rbac import UserRole
from faden_backend.db.models.users import User, end_sign_ins


async def members_of(session: AsyncSession, group_id: uuid.UUID) -> set[uuid.UUID]:
    """The people in the team *group_id*, however they came to be in it."""
    return set((await session.scalars(select(UserGroup.user_id).where(UserGroup.group_id == group_id))).all())


async def holders_of_role(session: AsyncSession, role_id: uuid.UUID) -> set[uuid.UUID]:
    """The people who have the role *role_id*: given to them, or through a team that has it."""
    direct = select(UserRole.user_id).where(UserRole.role_id == role_id)
    through_teams = (
        select(UserGroup.user_id)
        .join(GroupRole, GroupRole.group_id == UserGroup.group_id)
        .where(GroupRole.role_id == role_id)
    )
    return set((await session.scalars(direct.union(through_teams))).all())


async def rights_changed(
    session: AsyncSession,
    user_ids: Iterable[uuid.UUID],
    *,
    cause: str,
    actor_id: uuid.UUID | None = None,
    **details: object,
) -> list[uuid.UUID]:
    """End the sign-ins of the people *user_ids*, whose rights *cause* changed; record each. Returns them."""
    wanted = sorted(set(user_ids))
    if not wanted:
        return []
    users = list((await session.scalars(select(User).where(User.id.in_(wanted)))).all())
    for user in users:
        end_sign_ins(user)
    await session.flush()
    audit = AuditDAO(session)
    for user in users:
        await audit.log(
            action="user.sign_ins.ended",
            target_type="user",
            target_id=str(user.id),
            result=AuditResult.ALLOW,
            actor_id=actor_id,
            source=None if actor_id else "system",
            metadata_json=json.dumps({"email": user.email, "cause": cause, **details}, default=str),
        )
    return [user.id for user in users]
