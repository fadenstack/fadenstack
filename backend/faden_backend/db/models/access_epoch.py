"""The count of changes to who may do what: one row, moved by triggers (``db/access_epoch.py``).

Made by the migration ``4cc3ss`` with its function and triggers, and written only by them; no model reads it
(the gateway reads it with SQL of its own). It is declared here so the models describe the schema the
migrations make: without it, ``alembic check`` reports the table as removed, and an autogenerated migration
would drop it.
"""

from __future__ import annotations

from sqlalchemy import BigInteger, CheckConstraint, Column, SmallInteger, Table

from faden_backend.db.meta import meta

access_epoch = Table(
    "access_epoch",
    meta,
    Column("id", SmallInteger, primary_key=True, autoincrement=False),
    Column("epoch", BigInteger, nullable=False),
    CheckConstraint("id = 1"),
)
