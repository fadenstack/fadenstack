"""The count of changes to the system settings: one row, moved by triggers (``db/settings_epoch.py``).

Made by the migration ``s3tep0ch`` with its sequence, function and triggers, and written only by them; no
model reads it (``services/system_settings/runtime_sync.py`` reads it with SQL of its own). It is declared
here so the models describe the schema the migrations make: without it, ``alembic check`` reports the table
as removed, and an autogenerated migration would drop it.
"""

from __future__ import annotations

from sqlalchemy import BigInteger, CheckConstraint, Column, SmallInteger, Table

from faden_backend.db.meta import meta

system_settings_epoch = Table(
    "system_settings_epoch",
    meta,
    Column("id", SmallInteger, primary_key=True, autoincrement=False),
    Column("epoch", BigInteger, nullable=False),
    CheckConstraint("id = 1"),
)
