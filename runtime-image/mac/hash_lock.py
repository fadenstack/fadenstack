"""Add sha256 hashes to every line of the Mac runtime lock (``--require-hashes``).

- A PyPI pin (``name==version``) gets the sha256 of every file PyPI publishes
  for exactly that version (PyPI's JSON API). A release's files cannot be
  replaced on PyPI, so this is the set the installer may accept.
- A mirrored wheel (``name @ file://@WHEELS@/<file>``) gets its pin from
  ``deps.json``.

The build installs with ``uv pip install --require-hashes``, so a line without
a hash, or a file whose hash is not listed, fails the build.

Run when the lock changes; it rewrites requirements-lock.txt in place:

    python hash_lock.py
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOCK = HERE / "requirements-lock.txt"
PINS = HERE / "deps.json"

sys.path.insert(0, str(HERE))
from fetch_deps import requirements  # noqa: E402


def pypi_hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310 - pypi.org
        data = json.load(response)
    hashes = sorted({f["digests"]["sha256"] for f in data.get("urls") or []})
    if not hashes:
        raise SystemExit(f"{name}=={version}: PyPI lists no files")
    return hashes


def main() -> None:
    pins = {w["name"]: w for w in json.loads(PINS.read_text())["wheels"]}
    out: list[str] = []
    for requirement in requirements(LOCK.read_text()):
        if " @ " in requirement:
            name = requirement.split(" @ ", 1)[0]
            hashes = [pins[name]["sha256"]]
        else:
            name, version = requirement.split("==", 1)
            hashes = pypi_hashes(name, version)
        out.append(" \\\n".join([requirement, *(f"    --hash=sha256:{h}" for h in hashes)]))
        print(f"{len(hashes):3}  {requirement}", file=sys.stderr)
    LOCK.write_text(
        "# Generated by hash_lock.py from the pins below; install with --require-hashes.\n"
        + "\n".join(out) + "\n"
    )


if __name__ == "__main__":
    main()
