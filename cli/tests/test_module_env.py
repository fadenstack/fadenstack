"""``faden module enable`` switches a module on where the services look: ``.env``.

It used to record the module in faden.yaml only. The containers started and
the console listed the module as enabled, but the gateway and the backend kept
the compose file's ``*_ENABLED=false``, so the MCP and skills pages answered
"MCP module is not enabled." (release VM, 2026-09-25). And MCP encrypted what
it stored with the compose file's fixed dev key, the same for every install:
the CLI never generated one.
"""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml
from click.testing import CliRunner

from faden_cli.commands.module import module_group
from faden_cli.core.env_gen import SECRET_KEYS, default_env_vars, read_env_file, set_module_env

EXISTING = """# Generated by faden init
POSTGRES_PASSWORD=keep-me
FADEN_GATEWAY_MCP_SERVICE_TOKEN=the-token

# ── fadenstack Services ──
FADEN_GATEWAY_WORKERS_COUNT=2
"""


@pytest.fixture
def env(tmp_path: Path) -> Path:
    path = tmp_path / ".env"
    path.write_text(EXISTING, encoding="utf-8")
    return path


def test_enabling_mcp_switches_it_on_for_the_gateway_and_the_backend(env: Path) -> None:
    set_module_env(env, enable=["mcp"])
    values = read_env_file(env)
    assert values["FADEN_GATEWAY_MCP_ENABLED"] == "true"
    assert values["FADEN_BACKEND_MCP_ENABLED"] == "true"
    assert values["FADEN_GATEWAY_MCP_SERVICE_URL"] == "http://faden-mcp:8000"


def test_mcp_gets_a_key_of_its_own(env: Path) -> None:
    set_module_env(env, enable=["mcp"])
    key = read_env_file(env)["FADEN_MCP_ENCRYPTION_KEY"]
    assert key and key != "dev-mcp-encryption-key-change-me-32b"
    assert len(key) >= len("a 32-byte key encoded in base64..")


def test_a_token_group_is_completed_with_the_value_it_already_has(env: Path) -> None:
    """The gateway's token was there; the backend and MCP must hold the same one."""
    set_module_env(env, enable=["mcp"])
    values = read_env_file(env)
    assert values["FADEN_BACKEND_MCP_SERVICE_TOKEN"] == "the-token"
    assert values["FADEN_MCP_SERVICE_TOKEN"] == "the-token"


def test_everything_else_in_the_file_is_left_as_it_was(env: Path) -> None:
    set_module_env(env, enable=["mcp", "skills", "pii"])
    text = env.read_text(encoding="utf-8")
    assert text.startswith(EXISTING), "existing lines, comments and order untouched"
    assert read_env_file(env)["POSTGRES_PASSWORD"] == "keep-me"
    assert "\r\n" not in text


def test_enabling_twice_changes_nothing_the_second_time(env: Path) -> None:
    set_module_env(env, enable=["mcp"])
    first = env.read_text(encoding="utf-8")
    assert set_module_env(env, enable=["mcp"]) == []
    assert env.read_text(encoding="utf-8") == first, "the key is not regenerated"


def test_an_existing_switch_is_changed_in_place(env: Path) -> None:
    env.write_text(EXISTING + "FADEN_GATEWAY_MCP_ENABLED=false\n", encoding="utf-8")
    set_module_env(env, enable=["mcp"])
    assert env.read_text(encoding="utf-8").count("FADEN_GATEWAY_MCP_ENABLED=") == 1
    assert read_env_file(env)["FADEN_GATEWAY_MCP_ENABLED"] == "true"


def test_disabling_switches_it_off_and_keeps_its_secrets(env: Path) -> None:
    """Stored credentials may be encrypted with the key."""
    set_module_env(env, enable=["mcp"])
    key = read_env_file(env)["FADEN_MCP_ENCRYPTION_KEY"]
    set_module_env(env, disable=["mcp"])
    values = read_env_file(env)
    assert values["FADEN_GATEWAY_MCP_ENABLED"] == "false"
    assert values["FADEN_BACKEND_MCP_ENABLED"] == "false"
    assert values["FADEN_MCP_ENCRYPTION_KEY"] == key


def test_pii_is_switched_on_for_the_backend_too(env: Path) -> None:
    """The compose file defaults the backend's PII switch to false."""
    set_module_env(env, enable=["pii"])
    assert read_env_file(env)["FADEN_BACKEND_PII_ENABLED"] == "true"


def test_a_new_install_generates_the_mcp_key_and_keeps_it_on_regeneration() -> None:
    generated = default_env_vars()
    assert generated["FADEN_MCP_ENCRYPTION_KEY"]
    assert generated["FADEN_MCP_ENCRYPTION_KEY"] != default_env_vars()["FADEN_MCP_ENCRYPTION_KEY"]
    assert "FADEN_MCP_ENCRYPTION_KEY" in SECRET_KEYS


def test_the_command_writes_the_installs_env(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    install = tmp_path / "install"
    install.mkdir()
    (install / ".env").write_text(EXISTING, encoding="utf-8")
    config = tmp_path / "faden.yaml"
    config.write_text(yaml.safe_dump({"install_dir": str(install), "profiles": []}), encoding="utf-8")
    monkeypatch.setenv("FADEN_CONFIG", str(config))

    result = CliRunner().invoke(module_group, ["enable", "mcp", "skills"])

    assert result.exit_code == 0, result.output
    values = read_env_file(install / ".env")
    assert values["FADEN_BACKEND_MCP_ENABLED"] == "true"
    assert values["FADEN_BACKEND_SKILLS_ENABLED"] == "true"
    assert yaml.safe_load(config.read_text(encoding="utf-8"))["profiles"] == ["mcp", "skills"]
    assert "the-token" not in result.output, "secret values are never printed"
